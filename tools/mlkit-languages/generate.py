"""Regenerates ocr/MlKitLanguageCatalog.kt from Google's official ML Kit Text Recognition v2 language page.

  curl -sL 'https://developers.google.com/ml-kit/vision/text-recognition/v2/languages?hl=en' -o langs.html
  python3 -I tools/mlkit-languages/generate.py langs.html > app/src/main/java/io/github/wilsonnet/droidsentenceminer/ocr/MlKitLanguageCatalog.kt
"""
import html
import re
import sys

page = open(sys.argv[1], encoding='utf-8').read()
body = page[page.find('<article'):]
rows, section = [], None
for m in re.finditer(r'<h2[^>]*>(.*?)</h2>|<table.*?</table>', body, re.S):
    if m.group(0).startswith('<h2'):
        section = re.sub('<[^>]+>', '', m.group(1)).strip()
        continue
    category = {'Supported languages': 'SUPPORTED', 'Experimental languages': 'EXPERIMENTAL', 'Mapped languages': 'MAPPED'}.get(section)
    if not category:
        continue
    for r in re.findall(r'<tr>(.*?)</tr>', m.group(0), re.S):
        cells = [html.unescape(re.sub('<[^>]+>', '', c)).strip() for c in re.findall(r'<td[^>]*>(.*?)</td>', r, re.S)]
        if len(cells) < 4:
            continue
        native, english, code, notes = cells[:4]
        mapped = cells[4] if len(cells) > 4 else ''
        code = code.split(' ')[0]
        script = notes.split(';')[0].split('/')[0].strip()
        rows.append((code, english, native, category, script, notes, mapped))

def recognizer(script, notes, mapped):
    if 'Cyrillic' in mapped:
        return 'null'  # Google maps it to a Cyrillic model the Android v2 API does not ship
    return {'Latn': 'MlKitScript.LATIN', 'Hans': 'MlKitScript.CHINESE', 'Hant': 'MlKitScript.CHINESE',
            'Jpan': 'MlKitScript.JAPANESE', 'Kore': 'MlKitScript.KOREAN', 'Deva': 'MlKitScript.DEVANAGARI'}.get(script, 'null')

def q(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"').replace('$', '\\$') + '"'

print('''package io.github.wilsonnet.droidsentenceminer.ocr

// GENERATED by tools/mlkit-languages/generate.py from
// https://developers.google.com/ml-kit/vision/text-recognition/v2/languages — do not edit by hand.

/** Google's support level for a language in ML Kit Text Recognition v2. */
enum class MlKitSupport { SUPPORTED, EXPERIMENTAL, MAPPED }

/**
 * One row of the official language list. [recognizer] is the script model that reads it (several
 * languages share one model: Portuguese, English and Spanish all use [MlKitScript.LATIN]); null when
 * Google maps the language to a Cyrillic model, which the Android v2 API does not ship.
 */
data class MlKitLanguage(
    val code: String,
    val englishName: String,
    val nativeName: String,
    val support: MlKitSupport,
    /** ISO 15924 script from the page (Latn, Hans, Hant, Deva, Jpan, Kore, Cyrl). */
    val script: String,
    val recognizer: MlKitScript?,
    /** For [MlKitSupport.MAPPED]: what Google says it maps to (a language code or a script model). */
    val mappedTo: String? = null,
)

object MlKitLanguageCatalog {
    val all: List<MlKitLanguage> = listOf(''')
for code, english, native, category, script, notes, mapped in rows:
    extra = f', mappedTo = {q(mapped)}' if mapped else ''
    print(f'        MlKitLanguage({q(code)}, {q(english)}, {q(native)}, MlKitSupport.{category}, {q(script)}, {recognizer(script, notes, mapped)}{extra}),')
print('''    )

    private val byCode: Map<String, MlKitLanguage> = all.associateBy { it.code.lowercase() }

    /** Exact BCP-47 match first, then the base language (pt-BR → pt). */
    fun find(code: String): MlKitLanguage? {
        var key = code.trim().lowercase().replace('_', '-')
        if (key == "tl") key = "fil" // Google's documented Filipino alias.
        while (true) {
            byCode[key]?.let { return it }
            if ('-' !in key) return null
            key = key.substringBeforeLast('-')
        }
    }
}''')
